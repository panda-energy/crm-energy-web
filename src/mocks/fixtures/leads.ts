// Helpers internos — funciones puras para resolver stage_id en función
// del pipeline + status.
function stageFor(pipelineId: string, status: LeadStatus): string {
  if (pipelineId === EMPRESAS_PIPELINE_ID) {
    return EMPRESAS_STAGE_IDS[status];
  }
  return STAGE_IDS[status];
}

const U = USER_IDS;

/**
 * Tipo helper para que las plantillas inline sean compactas pero seguras
 * (TS strict; el spread final produce un `LeadOut` válido).
 */
type LeadTemplate = Omit<Lead, "tenant_id" | "currency" | "stage_id"> & {
  /** Optional override; default `stageFor(pipeline_id, status)`. */
  stage_id?: string;
};

function buildLead(t: LeadTemplate): Lead {
  return {
    tenant_id: TENANT_ID,
    currency: "EUR",
    stage_id: t.stage_id ?? stageFor(t.pipeline_id, t.status),
    id: t.id,
    pipeline_id: t.pipeline_id,
    owner_id: t.owner_id,
    first_name: t.first_name,
    last_name: t.last_name,
    email: t.email,
    phone_e164: t.phone_e164,
    company: t.company,
    cups: t.cups,
    status: t.status,
    source: t.source,
    source_ref: t.source_ref,
    tags: t.tags,
    custom_fields: t.custom_fields,
    estimated_value_cents: t.estimated_value_cents,
    last_contacted_at: t.last_contacted_at,
    position: t.position,
    created_at: t.created_at,
    updated_at: t.updated_at,
  };
}

// IDs determinísticos: `0a1b1c11-0000-0000-0000-0000000000NN` con NN 01..50.
function leadId(n: number): string {
  return `0a1b1c11-0000-0000-0000-${n.toString().padStart(12, "0")}`;
}

